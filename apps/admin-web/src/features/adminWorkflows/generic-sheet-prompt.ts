输出方式
同一场的多张图片合并读取，多场比赛分别整理。每场输出一个可下载的JSON文件，文件名为“日期-主队-客队.json”；也可输出包含多场对象的JSON数组。采用下方统一格式，球队使用图片中的名称，省去数据库ID和比赛编号。JSON字符串使用标准转义。

